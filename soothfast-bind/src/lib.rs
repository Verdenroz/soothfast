//! Soothfast binding engine: the exported Rust surface, bound natively.
//!
//! Where the SDK engine emits a client that talks to a server, this one
//! emits a glue crate that calls the code in-process. `#[soothfast::export]`
//! names what crosses over; rustdoc JSON says what shape it has; [`plan`]
//! turns the two into one language-neutral wrapper model that every backend
//! renders. Emission is deterministic, so `bind gen --check` can gate
//! staleness the way `sdk gen --check` does.

