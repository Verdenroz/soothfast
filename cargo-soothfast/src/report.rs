//! `cargo soothfast report render|changelog` — doc fragments produced from
//! recorded data: perf tables, trend charts, badges, and a living
//! CHANGELOG.md whose Unreleased section is regenerated in place.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use serde_json::Value;
use soothfast_report::{badges, changelog, perf_table, trend_chart};

use crate::config::{self, Config, Group, Settings};
use crate::{
    buildstamp, coverage_lang, coverage_report, docs_support, headrun, invoke, project_surface,
    refrun, runcache, trend, workspace,
};

pub fn run(args: &[String]) -> i32 {
    match args.first().map(String::as_str) {
        Some("render") => render(&args[1..]),
        Some("changelog") => changelog_cmd(&args[1..]),
        _ => {
            eprintln!(
                "soothfast: usage: cargo soothfast report render [--out DIR] | changelog -p PKG [-p PKG ...] [--against-ref REF]"
            );
            2
        }
    }
}

struct ReportArgs {
    pkg: Vec<String>,
    baseline: Option<String>,
    out: Option<PathBuf>,
    against_ref: Option<String>,
    features: Option<String>,
    bot_author: Option<String>,
    /// Non-Rust source trees besides the manifest's `[[project]]` entries.
    dirs: Vec<String>,
    lang: Option<String>,
}

impl ReportArgs {
    fn baseline_name(&self) -> &str {
        self.baseline.as_deref().unwrap_or("base")
    }

    /// Fill the flags the command line left unset from the resolved defaults.
    fn use_defaults(&mut self, defaults: Settings) {
        self.baseline = self.baseline.take().or(defaults.baseline);
        self.features = self.features.take().or(defaults.features);
    }
}

fn parse(args: &[String]) -> Result<ReportArgs, String> {
    let mut a = ReportArgs {
        pkg: Vec::new(),
        baseline: None,
        out: None,
        against_ref: None,
        features: None,
        bot_author: None,
        dirs: Vec::new(),
        lang: None,
    };
    let mut it = args.iter();
    while let Some(arg) = it.next() {
        match arg.as_str() {
            "-p" | "--package" => a
                .pkg
                .push(it.next().cloned().ok_or("-p needs a package name")?),
            "--baseline" => a.baseline = Some(it.next().cloned().ok_or("--baseline needs a name")?),
            "--out" => a.out = it.next().map(PathBuf::from),
            "--against-ref" => a.against_ref = it.next().cloned(),
            "--features" => a.features = it.next().cloned(),
            "--bot-author" => a.bot_author = it.next().cloned(),
            "--dir" => a.dirs.extend(it.next().cloned()),
            "--lang" => a.lang = it.next().cloned(),
            other => return Err(format!("unknown report arg {other:?}")),
        }
    }
    Ok(a)
}

fn load_baseline_required(name: &str) -> Result<Value, String> {
    match invoke::load_baseline(name) {
        Ok(Some(b)) => Ok(b),
        Ok(None) => Err(format!(
            "no baseline {name:?} — run `cargo soothfast measure --save-baseline {name}`"
        )),
        Err(e) => Err(e.to_string()),
    }
}

fn render(args: &[String]) -> i32 {
    let mut a = match parse(args) {
        Ok(a) => a,
        Err(e) => return err(&e),
    };
    match config::defaults_shared(&a.pkg, Group::Docs) {
        Ok(defaults) => a.use_defaults(defaults),
        Err(e) => return err(&e),
    }
    let baseline = match load_baseline_required(a.baseline_name()) {
        Ok(b) => b,
        Err(e) => return err(&e),
    };
    let root = match invoke::workspace_root() {
        Ok(r) => r,
        Err(e) => return err(&e.to_string()),
    };
    let out_dir = a.out.clone().unwrap_or_else(|| root.join("docs/perf"));
    let _ = std::fs::create_dir_all(&out_dir);
    let _ = std::fs::create_dir_all(out_dir.join("badges"));

    let mut summary =
        String::from("# Performance summary\n\n> Generated by `cargo soothfast report`\n\n");
    summary.push_str(&perf_table::markdown(&baseline));

    // Trend charts from the series, when it exists.
    let points = trend::load_points(&root).unwrap_or_else(|e| {
        eprintln!("report: no trend charts: {e}");
        Vec::new()
    });
    for (key, name, threshold, rel) in trend_chart::METRICS {
        if let Some(svg) = trend_chart::render(&points, key, name, *threshold, *rel) {
            let file = format!("trend-{name}.svg");
            if std::fs::write(out_dir.join(&file), svg).is_ok() {
                summary.push_str(&format!("\n![{name} trend]({file})\n"));
                println!("report: wrote {}", out_dir.join(&file).display());
            }
        }
    }

    // Badge reflects the last recorded gate verdict, never a hardcoded pass.
    let gate_passed = std::fs::read_to_string(root.join(".soothfast/gate-status.json"))
        .ok()
        .and_then(|t| serde_json::from_str::<Value>(&t).ok())
        .and_then(|v| v["passed"].as_bool());
    let gate = badges::gate_badge(gate_passed);
    let mut writes: Vec<(String, String)> = vec![
        ("summary.md".into(), summary),
        ("summary.html".into(), perf_table::html(&baseline)),
        ("badges/gate.json".into(), gate.to_string()),
        ("badges/gate.svg".into(), badges::svg_from(&gate)),
    ];
    if !a.pkg.is_empty() {
        match coverage_report::badge_files(&a.pkg, a.features.as_deref()) {
            Ok(files) => {
                for (stem, badge) in files {
                    writes.push((format!("badges/{stem}.json"), badge.to_string()));
                    writes.push((format!("badges/{stem}.svg"), badges::svg_from(&badge)));
                }
            }
            Err(e) => eprintln!("report: no coverage badges: {e}"),
        }
    }
    for (file, content) in &writes {
        if std::fs::write(out_dir.join(file), content).is_err() {
            return err(&format!("cannot write {file}"));
        }
        println!("report: wrote {}", out_dir.join(file).display());
    }
    0
}

/// One diff per package, headed by the crate name when there is more than
/// one — an unattributed `ADDED foo::bar` says nothing about where it landed.
fn surface_diffs(
    pkgs: &[String],
    refname: &str,
    features: impl Fn(&str) -> Option<String>,
) -> Result<String, String> {
    let mut out = String::new();
    for pkg in pkgs {
        let text = docs_support::surface_diff_text(pkg, refname, features(pkg).as_deref())?;
        if text.trim().is_empty() {
            continue;
        }
        if pkgs.len() > 1 {
            out.push_str(&format!("# {pkg}\n"));
        }
        out.push_str(text.trim_end());
        out.push_str("\n\n");
    }
    Ok(out)
}

/// Measure every `-p` package that carries a bench target at the merge-base
/// of `refname`, merged into one baseline-shaped document.
///
/// One worktree for all of them; packages without a bench target there are
/// skipped rather than failing the run, since a newly measured crate simply
/// has no earlier side to compare against. `Ok(None)` when that leaves
/// nothing measured, which renders the current-only table as before. A
/// package that cannot be measured there is warned about and left out of
/// the table; only a configuration error is an `Err`.
///
/// When HEAD is the merge-base nothing is measured: the figures are
/// `baseline`'s.
fn measure_ref(
    a: &ReportArgs,
    refname: &str,
    root: &Path,
    config: &Config,
    baseline: &Value,
) -> Result<Option<Value>, String> {
    let sha = match refrun::anchor(root, refname) {
        refrun::Anchor::Head => {
            println!("report: no commits since {refname}, so its figures are the baseline's own");
            return Ok(Some(baseline.clone()));
        }
        refrun::Anchor::At(sha) => sha,
    };
    let mut packages = Vec::new();
    for pkg in &a.pkg {
        let common = refrun::common(config, pkg)?;
        let stamp = buildstamp::capture(&common, None);
        let key = (!sha.is_empty()).then(|| runcache::report_key(&sha, &common, &stamp));
        packages.push(RefPackage {
            pkg,
            common,
            stamp,
            key,
        });
    }
    let (mut docs, unmeasured) = stored_ref_docs(&packages, &sha, refname);
    let mut failed = Vec::new();
    if !unmeasured.is_empty() {
        let (measured, why) = measure_in_worktree(&unmeasured, refname);
        docs.extend(measured);
        failed = why;
    }
    Ok(ref_figures(&docs, &failed, refname))
}

/// A package the worktree could not measure, and why.
type Failed = (String, String);

/// The figures the draft compares the baseline with. A package that failed
/// to measure gets a warning and no rows. When nothing else was measured the
/// reference is empty, so the draft has no table instead of the current one.
fn ref_figures(docs: &[Value], failed: &[Failed], refname: &str) -> Option<Value> {
    for (pkg, why) in failed {
        println!("{}", left_out(refname, pkg, why));
    }
    merged_ref_doc(docs)
        .or_else(|| (!failed.is_empty()).then(|| serde_json::json!({ "version": 1, "items": {} })))
}

/// The warning for a package whose release could not be measured.
fn left_out(refname: &str, pkg: &str, why: &str) -> String {
    let why = why.lines().collect::<Vec<_>>().join(" ");
    format!("::warning::report: perf delta against {refname} left out for {pkg}: {why}")
}

/// One package of a reference measurement: the flags it is measured under
/// and the key its measurement is kept under, when the commit is known.
struct RefPackage<'a> {
    pkg: &'a str,
    common: invoke::CommonArgs,
    stamp: buildstamp::BuildStamp,
    key: Option<String>,
}

/// The measurements the run store already holds, and the packages it holds
/// none for.
fn stored_ref_docs<'a>(
    packages: &'a [RefPackage<'a>],
    sha: &str,
    refname: &str,
) -> (Vec<Value>, Vec<&'a RefPackage<'a>>) {
    let mut docs = Vec::new();
    let mut unmeasured = Vec::new();
    for package in packages {
        let pkg = package.pkg;
        let Some(key) = &package.key else {
            unmeasured.push(package);
            continue;
        };
        if let Some(doc) = runcache::stored_report(key) {
            println!("report: reusing the stored measurement of {refname} for {pkg}");
            docs.push(doc);
        } else if let Some(doc) = refrun::recorded_for(&package.common, &package.stamp, sha, key) {
            println!("report: reusing the gate's recorded run of {refname} for {pkg}");
            docs.push(doc);
        } else {
            unmeasured.push(package);
        }
    }
    (docs, unmeasured)
}

/// Measures `packages` in one worktree at the merge-base of `refname` and
/// keeps each measurement under its key. A package that fails is returned
/// with its reason; a worktree that cannot be made fails them all.
fn measure_in_worktree(packages: &[&RefPackage], refname: &str) -> (Vec<Value>, Vec<Failed>) {
    println!("report: measuring {refname} in a worktree");
    let measured = invoke::with_merge_base_worktree(refname, |wt| {
        Ok(measure_each(packages, |package| measure_at(package, wt)))
    });
    let (runs, failed) = match measured {
        Ok(measured) => measured,
        Err(why) => {
            let all = packages.iter().map(|p| (p.pkg.to_string(), why.clone()));
            (Vec::new(), all.collect())
        }
    };
    let mut docs = Vec::new();
    for (package, run) in runs {
        let doc = headrun::ref_doc(&run);
        if let Some(key) = &package.key {
            runcache::keep_report(key, &doc);
        }
        docs.push(doc);
    }
    (docs, failed)
}

/// The run of each package `measure` gives one for, and the packages it
/// failed on. `Ok(None)` is a package with nothing to measure there.
fn measure_each<'a, 'p>(
    packages: &[&'a RefPackage<'p>],
    mut measure: impl FnMut(&RefPackage) -> Result<Option<invoke::Run>, String>,
) -> (Vec<(&'a RefPackage<'p>, invoke::Run)>, Vec<Failed>) {
    let mut runs = Vec::new();
    let mut failed = Vec::new();
    for package in packages {
        match measure(package) {
            Ok(Some(run)) => runs.push((*package, run)),
            Ok(None) => {}
            Err(why) => failed.push((package.pkg.to_string(), why)),
        }
    }
    (runs, failed)
}

/// `package` measured in the worktree `wt`, or `None` when it has no bench
/// target there.
fn measure_at(package: &RefPackage, wt: &Path) -> Result<Option<invoke::Run>, String> {
    let common = &package.common;
    let target = common.target.as_deref().unwrap_or("soothfast");
    if !workspace::has_bench_target(package.pkg, target, Some(wt)).map_err(|e| e.to_string())? {
        return Ok(None);
    }
    let records = invoke::run_bench_in(common, &[], Some(wt)).map_err(|e| e.to_string())?;
    Ok(Some(invoke::collect(&records)))
}

/// The items of every document in one baseline-shaped document, under the
/// largest noise floor among them. `None` when there are no documents.
fn merged_ref_doc(docs: &[Value]) -> Option<Value> {
    if docs.is_empty() {
        return None;
    }
    let mut items = serde_json::Map::new();
    let mut noise: Option<f64> = None;
    for doc in docs {
        if let Some(obj) = doc["items"].as_object() {
            items.extend(obj.clone());
        }
        if let Some(n) = doc["noise_pct"].as_f64() {
            noise = Some(noise.map_or(n, |m: f64| m.max(n)));
        }
    }
    let mut doc = serde_json::json!({ "version": 1, "items": items });
    if let Some(n) = noise {
        doc["noise_pct"] = serde_json::json!(n);
    }
    Some(doc)
}

fn changelog_cmd(args: &[String]) -> i32 {
    let mut a = match parse(args) {
        Ok(a) => a,
        Err(e) => return err(&e),
    };

    let root = match invoke::workspace_root() {
        Ok(r) => r,
        Err(e) => return err(&e.to_string()),
    };
    let config = match Config::load(&root) {
        Ok(c) => c,
        Err(e) => return err(&e),
    };
    let cfg = match config.changelog() {
        Ok(c) => c,
        Err(e) => return err(&e),
    };
    if a.pkg.is_empty() {
        a.pkg = cfg.packages;
    }
    if a.pkg.is_empty() {
        return err("report changelog needs -p PKG");
    }
    let gate_cfg = match config.gate() {
        Ok(g) => g,
        Err(e) => return err(&e),
    };
    let own: BTreeMap<String, String> = match config.resolve_shared(&a.pkg, Group::Docs) {
        Ok((defaults, each)) => {
            a.use_defaults(defaults);
            each.into_iter()
                .filter_map(|(pkg, s)| Some((pkg, s.features?)))
                .collect()
        }
        Err(e) => return err(&e),
    };
    let features_of = |pkg: &str| {
        let table = a.features.clone().or_else(|| own.get(pkg).cloned());
        resolve_features(table, cfg.features.as_deref(), gate_cfg.features.as_deref())
    };
    let path = a.out.clone().unwrap_or_else(|| root.join("CHANGELOG.md"));
    let existing = std::fs::read_to_string(&path).unwrap_or_default();

    // A release PR renames the top heading away from "Unreleased" before
    // its own CI run gets here — regenerating on top of that would inject
    // a fresh Unreleased section the PR is already in the middle of
    // retiring, which then has to be hand-deleted after every release.
    if changelog_already_cut(&existing, a.against_ref.as_deref()) {
        println!(
            "report: {} already has a released top section — nothing to regenerate",
            path.display()
        );
        return 0;
    }
    if a.against_ref.is_none()
        && let Some(prior) = prior_release_ref(&existing)
    {
        let msg = match prior {
            PriorRelease::Drafted(refname) => format!(
                "{} already has a prior release drafted against {refname}, but no \
                 --against-ref was given; regenerating would replace it with an empty \
                 initial-surface section. Pass --against-ref {refname} (tags may not \
                 have been fetched).",
                path.display()
            ),
            PriorRelease::Released(version) if !version.is_empty() => format!(
                "{} already has a released {version} section, but no --against-ref \
                 was given; regenerating would replace the Unreleased section with an \
                 empty initial-surface one. Pass --against-ref for the tag {version} \
                 shipped under (tags may not have been fetched).",
                path.display()
            ),
            PriorRelease::Released(_) => format!(
                "{} already has a released section, but no --against-ref was given; \
                 regenerating would replace the Unreleased section with an empty \
                 initial-surface one. Pass --against-ref for the tag it shipped under \
                 (tags may not have been fetched).",
                path.display()
            ),
        };
        return err(&msg);
    }

    let baseline = match load_baseline_required(a.baseline_name()) {
        Ok(b) => b,
        Err(e) => return err(&e),
    };

    // Without a reference there is no earlier surface to diff against, so
    // the release is described by what it contains. A facade crate's own
    // surface is thin; pass every crate whose API ships.
    let targets = if cfg.api_surface || !a.dirs.is_empty() || a.lang.is_some() {
        match coverage_lang::targets(&root, &a.dirs, a.lang.as_deref()) {
            Ok(t) => t,
            Err(e) => return err(&e),
        }
    } else {
        Vec::new()
    };
    let (mut diff_text, mut entries) = match &a.against_ref {
        Some(refname) => match surface_diffs(&a.pkg, refname, features_of) {
            Ok(t) => (t, Vec::new()),
            Err(e) => return err(&e),
        },
        None => {
            let mut all = Vec::new();
            for pkg in &a.pkg {
                match docs_support::surface_entries(pkg, features_of(pkg).as_deref()) {
                    Ok(e) => all.extend(e),
                    Err(e) => return err(&e),
                }
            }
            (String::new(), all)
        }
    };
    for target in &targets {
        match &a.against_ref {
            Some(refname) => match project_surface::diff_text(&root, target, refname) {
                Ok(t) if t.is_empty() => {}
                Ok(t) => diff_text.push_str(&format!("# {}\n{}\n", target.label, t.trim_end())),
                Err(e) => return err(&e),
            },
            None => match project_surface::inventory(target) {
                Ok(e) => entries.extend(e),
                Err(e) => return err(&e),
            },
        }
    }
    // Measuring the ref turns the Performance section from a point-in-time
    // snapshot into "what moved", which is what a changelog reader wants and
    // what keeps a no-op merge from rewriting the whole table.
    let ref_baseline = match &a.against_ref {
        Some(refname) => match measure_ref(&a, refname, &root, &config, &baseline) {
            Ok(b) => b,
            Err(e) => return err(&e),
        },
        None => None,
    };
    let bot_author = resolve_bot_author(a.bot_author.take(), cfg.bot_author.as_deref());
    let changes = match &a.against_ref {
        Some(refname) => match merged_changes(refname, &bot_author) {
            Ok(c) => c,
            Err(e) => return err(&e),
        },
        None => Vec::new(),
    };
    let text = changelog::draft(&changelog::DraftInputs {
        changes: &changes,
        icons: &cfg.icons,
        api: match &a.against_ref {
            Some(refname) => changelog::ApiSection::Diff {
                against: refname,
                text: &diff_text,
            },
            None => changelog::ApiSection::Initial(&entries),
        },
        old_baseline: ref_baseline.as_ref(),
        new_baseline: &baseline,
        thresholds: changelog::PerfThresholds {
            instructions_pct: crate::gate::INSTRUCTIONS_THRESHOLD_PCT,
            allocs_pct: crate::gate::ALLOC_THRESHOLD_PCT as f64,
        },
    });

    if std::fs::write(&path, merge_changelog(&existing, &text)).is_err() {
        return err(&format!("cannot write {}", path.display()));
    }
    println!("report: regenerated {}", path.display());
    0
}

/// The features `report changelog` reads the API surface under: the command
/// line first, then `[changelog] features`, then `[gate] features`.
pub(crate) fn resolve_features(
    cli: Option<String>,
    changelog: Option<&str>,
    gate: Option<&str>,
) -> Option<String> {
    cli.or_else(|| changelog.or(gate).map(str::to_string))
}

/// The author `report changelog` leaves out: the command line first, then
/// `[changelog] bot-author`, then the slug the action ships with.
fn resolve_bot_author(cli: Option<String>, config: Option<&str>) -> String {
    cli.unwrap_or_else(|| config.unwrap_or(DEFAULT_BOT_AUTHOR).to_string())
}

/// Author of the soothfast bot's own commits, as `action/land.sh` commits
/// them under the default `bot-slug`.
const DEFAULT_BOT_AUTHOR: &str = "soothfast-bot[bot]";

/// Separates author from subject in the log format below. A unit separator
/// occurs in neither field.
const LOG_FIELD_SEP: char = '\u{1f}';

/// Subjects from `%an%x1f%s` log lines, minus the ones `bot_author` wrote.
/// That one author and no other: `dependabot[bot]` writes real changelog
/// entries, and a rule matching every `[bot]` would delete them all.
fn subjects_excluding_author(log: &str, bot_author: &str) -> Vec<String> {
    log.lines()
        .filter_map(|line| line.split_once(LOG_FIELD_SEP))
        .filter(|(author, _)| *author != bot_author)
        .map(|(_, subject)| subject.to_string())
        .collect()
}

/// Conventional-commit subjects merged since `refname`, newest first, with
/// the soothfast bot's own regeneration commits left out. Read from the log
/// rather than a forge API: every merge lands as a squash whose subject
/// already carries its pull request number, and whose author survives it.
fn merged_changes(refname: &str, bot_author: &str) -> Result<Vec<changelog::Change>, String> {
    let range = format!("{refname}..HEAD");
    let log = invoke::git(&["log", "--format=%an%x1f%s", &range]).map_err(|e| e.to_string())?;
    let subjects = subjects_excluding_author(&log, bot_author);
    let unparsed = changelog::unparsed_subjects(&subjects);
    if !unparsed.is_empty() {
        println!(
            "report: {} subject(s) since {refname} are not conventional commits and are left out:",
            unparsed.len()
        );
        for subject in unparsed {
            println!("  {subject}");
        }
    }
    Ok(changelog::changes_from_subjects(&subjects))
}

/// True only for the specific race the guard exists to catch: a release PR
/// that has renamed the top heading away from "Unreleased" in its own
/// branch, running before the matching tag exists. That PR's own CI still
/// diffs against the *previous* release's tag, so regenerating would inject
/// a fresh Unreleased section duplicating the one it's mid-flight retiring.
///
/// A normal PR sometime after that release has the same top heading, but by
/// then `against_ref` (the latest tag reachable from HEAD) has caught up to
/// match it — that's the signal a new Unreleased section is legitimately
/// due, not a race, so this returns false and regeneration proceeds.
///
/// A file with no `## ` heading yet, or one still under "Unreleased", is
/// never "already cut".
fn changelog_already_cut(existing: &str, against_ref: Option<&str>) -> bool {
    let Some(heading) = existing.lines().find_map(|l| l.strip_prefix("## ")) else {
        return false;
    };
    let heading = heading.trim_start();
    if heading.starts_with("Unreleased") || heading.starts_with("[Unreleased]") {
        return false;
    }
    let heading_version = heading
        .split_whitespace()
        .next()
        .unwrap_or("")
        .trim_start_matches('[')
        .split(']')
        .next()
        .unwrap_or("");
    match against_ref {
        Some(r) => heading_version != r.trim_start_matches('v'),
        // No tag at all reachable from HEAD only happens for a repo's very
        // first release, still mid-flight in its own PR — the same race,
        // just without a previous tag to compare against. Stay conservative.
        None => true,
    }
}

/// What a populated Unreleased section says about a prior release, when
/// `existing` shows one and `--against-ref` was left out. `Drafted` is the
/// ref an `Unreleased (draft vs X)` heading already names; `Released` is
/// the version on a released `## ` heading below it, not necessarily a
/// git ref (this repo's own headings are bare versions like `0.3.3`, not
/// tags like `v0.3.3`), so a caller shouldn't hand it to `--against-ref`
/// as-is. `None` means there is nothing to lose: an empty or missing file,
/// or an Unreleased heading that never named a ref.
#[derive(Debug, PartialEq)]
enum PriorRelease {
    Drafted(String),
    Released(String),
}

fn prior_release_ref(existing: &str) -> Option<PriorRelease> {
    let mut headings = existing.lines().filter_map(|l| l.strip_prefix("## "));
    let top = headings.next()?.trim_start();
    if let Some(rest) = top.strip_prefix("Unreleased (draft vs ") {
        return rest
            .split(')')
            .next()
            .map(|r| PriorRelease::Drafted(r.to_string()));
    }
    let is_unreleased = |h: &str| h.starts_with("Unreleased") || h.starts_with("[Unreleased]");
    let released = if is_unreleased(top) {
        headings.find(|h| !is_unreleased(h.trim_start()))?
    } else {
        top
    };
    let version = released
        .split_whitespace()
        .next()
        .unwrap_or("")
        .trim_start_matches('[')
        .split(']')
        .next()
        .unwrap_or("");
    Some(PriorRelease::Released(version.to_string()))
}

const NOTES_START: &str = "<!-- soothfast:notes -->";
const NOTES_END: &str = "<!-- /soothfast:notes -->";

/// Prompts for the sections a reader wants and no measurement can supply.
/// Commented out so an unfilled block renders as nothing.
const NOTES_SCAFFOLD: &str = "\
<!-- ### Overview -->
<!-- What this release means for someone using it. One paragraph. -->

<!-- ### Upgrade notes -->
<!-- What a consumer has to do. \"Nothing\" is a useful answer. -->
";

/// A maintainer's hand-written prose survives regeneration by living inside
/// a `soothfast:notes` marker pair in the Unreleased section; everything
/// else there is bot-owned and gets replaced. Malformed markers (missing or
/// out-of-order) are treated as no notes, rather than guessing.
fn extract_notes(unreleased: &str) -> Option<&str> {
    let start = unreleased.find(NOTES_START)? + NOTES_START.len();
    let end = unreleased[start..].find(NOTES_END)? + start;
    Some(unreleased[start..end].trim())
}

/// Replace the previous Unreleased section with the fresh draft, keeping
/// released sections — regeneration is idempotent, one Unreleased at a time.
/// Keep-a-Changelog files are respected: the preamble prose before the first
/// section survives, and a bracketed `## [Unreleased]` heading counts as the
/// Unreleased section to replace. A `soothfast:notes` block inside the old
/// Unreleased section rides along into the new one (see `extract_notes`).
fn merge_changelog(existing: &str, draft: &str) -> String {
    let mut preamble = String::new();
    let mut released = String::new();
    let mut unreleased = String::new();
    let mut seen_section = false;
    let mut keep = false;
    for line in existing.lines() {
        if let Some(h) = line.strip_prefix("## ") {
            seen_section = true;
            let h = h.trim_start();
            keep = !(h.starts_with("Unreleased") || h.starts_with("[Unreleased]"));
        }
        if !seen_section {
            // The title is re-emitted below; keep any other preamble prose.
            if line.trim() != "# Changelog" {
                preamble.push_str(line);
                preamble.push('\n');
            }
        } else if keep {
            released.push_str(line);
            released.push('\n');
        } else {
            unreleased.push_str(line);
            unreleased.push('\n');
        }
    }
    let draft = &changelog::keep_stable_rows(draft, &unreleased);
    let mut doc = String::from("# Changelog\n");
    let pre = preamble.trim();
    if !pre.is_empty() {
        doc.push('\n');
        doc.push_str(pre);
        doc.push('\n');
    }
    doc.push('\n');
    match extract_notes(&unreleased).filter(|n| !n.is_empty()) {
        Some(notes) => {
            // Splice right after the heading line, ahead of the bot's own
            // API-surface/Performance sections.
            let (heading, rest) = draft.split_once('\n').unwrap_or((draft, ""));
            doc.push_str(heading);
            doc.push('\n');
            doc.push('\n');
            doc.push_str(NOTES_START);
            doc.push('\n');
            doc.push_str(notes);
            doc.push('\n');
            doc.push_str(NOTES_END);
            doc.push('\n');
            doc.push('\n');
            doc.push_str(rest.trim_start_matches('\n'));
        }
        None => {
            let (heading, rest) = draft.split_once('\n').unwrap_or((draft, ""));
            doc.push_str(heading);
            doc.push_str("\n\n");
            doc.push_str(NOTES_START);
            doc.push('\n');
            doc.push_str(NOTES_SCAFFOLD);
            doc.push_str(NOTES_END);
            doc.push_str("\n\n");
            doc.push_str(rest.trim_start_matches('\n'));
        }
    }
    doc.push('\n');
    if !released.is_empty() {
        doc.push('\n');
        doc.push_str(released.trim_end());
        doc.push('\n');
    }
    doc
}

fn err(msg: &str) -> i32 {
    eprintln!("soothfast: {msg}");
    2
}

